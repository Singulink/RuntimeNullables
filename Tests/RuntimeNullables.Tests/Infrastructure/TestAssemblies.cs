using System.Collections.Generic;
using System.Linq;
using System.Runtime.CompilerServices;
using Mono.Cecil;

namespace RuntimeNullables.Tests.Infrastructure;

/// <summary>
/// The test assemblies, which are woven when they're built. Each project file says what the assembly is for and which settings it's woven with.
/// </summary>
internal static class TestAssemblies
{
    public static IReadOnlyList<string> Names { get; } =
    [
        "TestAssembly",
        "TestAssemblyNonPublic",
        "TestAssemblyPointers",
#if NET11_0_OR_GREATER
        "TestAssemblyRuntimeAsync",
#endif
        "TestAssemblySigned",
        "TestAssemblyThrowHelpers",
    ];

    /// <summary>
    /// Gets the test assembly names as dynamic data for tests that take an assembly name.
    /// </summary>
    public static IEnumerable<object[]> All => Names.Select(n => new object[] { n });

    /// <summary>
    /// Gets the full names of the woven test assemblies' top-level types that weren't generated by the compiler, as dynamic data for tests that take an
    /// assembly name and a type name.
    /// </summary>
    public static IEnumerable<object[]> AllTypes => Names.SelectMany(n => GetTypeNames(n).Select(t => new object[] { n, t }));

    private static List<string> GetTypeNames(string assemblyName)
    {
        using var module = ModuleDefinition.ReadModule(TestFiles.GetWovenAssemblyPath(assemblyName));

        return module.Types
            .Where(t => t.Name != "<Module>" && !t.CustomAttributes.Any(a => a.AttributeType.FullName == typeof(CompilerGeneratedAttribute).FullName))
            .Select(t => t.FullName)
            .ToList();
    }
}
